import { prisma } from "../lib/prisma";
import { TimetableService } from "./timetable.service";
import bcrypt from "bcryptjs";
import { EmailService } from "./email.service";
import { CacheService } from "./cache.service";

export class UserService { 

  static async deleteAccount(userId: string) {
    const user = await prisma.user.findUnique({ where: { id: userId } });
    const fsPromises = require('fs/promises');
    const path = require('path');

    // 1. Delete stored documents from filesystem
    const docs = await prisma.storedDocument.findMany({ where: { userId } });
    for (const doc of docs) {
      if (doc.fileUrl && doc.fileUrl.startsWith('/uploads/')) {
        try {
          const filePath = path.join(process.cwd(), doc.fileUrl);
          await fsPromises.unlink(filePath).catch(() => {});
        } catch(e) {}
      }
    }

    // 2. Clean up share transfers generated by this user
    try {
      await prisma.shareTransfer.deleteMany({ where: { senderUserId: userId } });
    } catch (e) {}

    // 3. Clean up any assignments or notes referencing classrooms created by this user
    // (since Assignment.classroom and Note.classroom do not have onDelete: Cascade)
    try {
      await prisma.assignment.deleteMany({ where: { classroom: { createdById: userId } } });
      await prisma.note.deleteMany({ where: { classroom: { createdById: userId } } });
    } catch (e) {}

    // 4. Delete exports, assignments, and notes belonging to the user
    // (since Export.subject, Assignment.subject, Note.subject do not have onDelete: Cascade)
    try {
      await prisma.export.deleteMany({ where: { OR: [{ userId }, { semester: { userId } }, { subject: { userId } }] } });
      await prisma.assignmentCompletion.deleteMany({ where: { userId } });
      await prisma.assignment.deleteMany({ where: { OR: [{ userId }, { subject: { userId } }] } });
      await prisma.note.deleteMany({ where: { OR: [{ userId }, { subject: { userId } }] } });
    } catch (e) {}

    // 4b. Delete attendance, timetable overrides, timetable slots, events, classrooms, subjects, and semesters
    // in leaf-to-root order to prevent PostgreSQL RESTRICT foreign key errors (e.g. Attendance -> TimetableSlot/Override)
    try {
      await prisma.attendance.deleteMany({ where: { userId } });
      await prisma.timetableOverride.deleteMany({ where: { semester: { userId } } });
      await prisma.timetableSlot.deleteMany({ where: { semester: { userId } } });
      await prisma.event.deleteMany({ where: { OR: [{ userId }, { semester: { userId } }] } });
      await prisma.classroomMember.deleteMany({ where: { userId } });
      await prisma.classroom.deleteMany({ where: { createdById: userId } });
      await prisma.subject.deleteMany({ where: { userId } });
      await prisma.semester.deleteMany({ where: { userId } });
    } catch (e) {}

    // 5. Invalidate user cache before deleting
    try {
      const { CacheService } = require("./cache.service");
      await CacheService.invalidateUser(userId);
    } catch (e) {}

    // 6. Delete the user (this cascades to mostly everything else like attendance, subjects, etc.)
    await prisma.user.delete({ where: { id: userId } });

    if (user && user.email) {
      EmailService.sendAccountDeletionEmail(user.email, user.name || "User").catch(console.error);
    }
  }

  static async getProfile(userId: string) {
    const user = await prisma.user.findUnique({
      where: { id: userId },
      select: {
        id: true,
        email: true,
        name: true,
        rollNumber: true,
        avatarUrl: true,
        role: true,
        department: true,
        batch: true,
        targetAttendance: true,
        theme: true,
        gender: true,
        birthday: true,
        passwordHash: true,
        googleId: true,
        createdAt: true,
      },
    });
    if (!user) throw new Error("User not found");
    const { passwordHash, ...rest } = user;
    return { ...rest, hasPassword: !!passwordHash };
  }

  static async updateProfile(userId: string, data: any) {
    const { newPassword, oldPassword } = data || {};

    // SEC-FIX: Strictly allowlist user-editable profile fields to prevent mass assignment
    // (e.g. role escalation, email hijack, or direct passwordHash overwrite).
    const allowedFields = [
      "name",
      "rollNumber",
      "avatarUrl",
      "department",
      "batch",
      "targetAttendance",
      "theme",
      "gender",
      "birthday",
      "autoTerminateMonths",
    ] as const;

    const updateData: Record<string, any> = {};
    for (const key of allowedFields) {
      if (data && data[key] !== undefined) {
        updateData[key] = data[key];
      }
    }

    let hadExistingPassword = false;
    let targetUserEmail = "";
    let targetUserName = "";

    if (newPassword) {
      if (typeof newPassword !== "string" || newPassword.length < 6) {
        throw new Error("New password must be at least 6 characters");
      }
      const user = await prisma.user.findUnique({ where: { id: userId } });
      if (!user) throw new Error("User not found");

      hadExistingPassword = !!user.passwordHash;
      targetUserEmail = user.email;
      targetUserName = user.name || "Student";
      
      if (user.passwordHash) {
        if (!oldPassword) throw new Error("Current password is required to set a new password");
        const isValid = await bcrypt.compare(String(oldPassword), user.passwordHash);
        if (!isValid) throw new Error("Incorrect current password");
      }
      
      updateData.passwordHash = await bcrypt.hash(newPassword, 10);
    }

    if (updateData.targetAttendance !== undefined) {
      await prisma.subject.updateMany({
        where: { userId },
        data: { targetAttendance: null }
      });
    }

    if (updateData.birthday !== undefined) {
      updateData.lastBirthdayEmailSentAt = null;
    }

    const updatedUser = await prisma.user.update({
      where: { id: userId },
      data: updateData,
      select: {
        id: true,
        email: true,
        name: true,
        rollNumber: true,
        avatarUrl: true,
        role: true,
        department: true,
        batch: true,
        targetAttendance: true,
        theme: true,
        gender: true,
        birthday: true,
        passwordHash: true,
      },
    });

    const { passwordHash, ...rest } = updatedUser;

    if (newPassword && targetUserEmail) {
      const timeStr = new Date().toLocaleString("en-IN", {
        timeZone: "Asia/Kolkata",
        dateStyle: "medium",
        timeStyle: "short",
      });

      if (hadExistingPassword) {
        EmailService.sendPasswordChangedEmail(targetUserEmail, targetUserName, timeStr).catch((err) => {
          console.error("[UserService:Email] Failed to dispatch password changed email:", err);
        });
      } else {
        EmailService.sendPasswordCreatedEmail(targetUserEmail, targetUserName, timeStr).catch((err) => {
          console.error("[UserService:Email] Failed to dispatch password created email:", err);
        });
      }
    }

    return { ...rest, hasPassword: !!passwordHash };
  }

  static async getSessions(userId: string, sessionId?: string) {
    // Non-blocking asynchronous garbage collection in the background
    setImmediate(async () => {
      try {
        const user = await prisma.user.findUnique({ where: { id: userId }, select: { autoTerminateMonths: true } }) as any;
        await prisma.refreshToken.deleteMany({
          where: {
            userId,
            expiresAt: { lt: new Date() },
            id: sessionId ? { not: sessionId } : undefined
          }
        });

        if (user?.autoTerminateMonths) {
          const cutoffDate = new Date();
          cutoffDate.setMonth(cutoffDate.getMonth() - user.autoTerminateMonths);
          await prisma.refreshToken.deleteMany({
            where: {
              userId,
              lastActive: { lt: cutoffDate },
              id: sessionId ? { not: sessionId } : undefined
            }
          });
        }
      } catch (error) {}
    });

    const rawSessions = await CacheService.getOrSet(userId, "user:sessions", async () => {
      const now = new Date();
      const sessions = await prisma.refreshToken.findMany({
        where: {
          userId,
          expiresAt: { gt: now }
        },
        orderBy: { lastActive: "desc" },
        select: {
          id: true,
          userAgent: true,
          ipAddress: true,
          location: true,
          deviceType: true,
          os: true,
          browser: true,
          lastActive: true,
          createdAt: true
        }
      });

      return sessions.map((s: any) => {
        let { os, browser, deviceType, location } = s;

        // Normalize stale "web" os value stored in old sessions
        if (os === 'web') {
          os = 'Browser';
          browser = 'Browser';
          deviceType = 'desktop';
        }

        // Normalize stale "Unknown OS" or null
        if (!os || os === 'Unknown OS') {
          os = 'Unknown Device';
        }

        // If location looks like a raw geoip dump with just country code or unknown, prefer showing nothing
        if (location === 'Unknown Location' || location === ', ') {
          location = null;
        }

        return {
          ...s,
          os,
          browser,
          deviceType,
          location
        };
      });
    });

    return (rawSessions || []).map((s: any) => ({
      ...s,
      isCurrent: s.id === sessionId
    }));
  }

  static async revokeSession(userId: string, sessionId: string) {
    await prisma.refreshToken.deleteMany({ where: { userId, id: sessionId } });
    CacheService.del(userId, "user:sessions").catch(() => {});
    return { success: true };
  }

  static async revokeAllOtherSessions(userId: string, currentSessionId: string) {
    await prisma.refreshToken.deleteMany({ where: { userId, id: { not: currentSessionId } } });
    CacheService.del(userId, "user:sessions").catch(() => {});
    return { success: true };
  }

  static async resetTimetable(userId: string) {
    // 1. Clean up timetable overrides (extra classes, cancelled, rescheduled)
    await prisma.timetableOverride.deleteMany({
      where: { semester: { userId } }
    });

    // 2. Soft-archive active timetable slots by setting validUntil = now
    // This removes them from active schedule while preserving the archived timetable version
    await prisma.timetableSlot.updateMany({
      where: { semester: { userId }, validUntil: null },
      data: { validUntil: new Date() }
    });

    return { success: true, message: "Timetable schedule cleared and archived successfully." };
  }

  static async resetEvents(userId: string) {
    await prisma.event.deleteMany({
      where: {
        OR: [
          { userId },
          { semester: { userId } }
        ]
      }
    });
    return { success: true, message: "Events cleared successfully." };
  }

  static async resetData(userId: string) {
    const fsPromises = require('fs/promises');
    const path = require('path');

    // 1. Fetch document paths and trigger async filesystem unlinks concurrently
    const docs = await prisma.storedDocument.findMany({ where: { userId }, select: { fileUrl: true } });
    const unlinkPromises = docs.map((doc: any) => {
      if (doc.fileUrl && doc.fileUrl.startsWith('/uploads/')) {
        const filePath = path.join(process.cwd(), doc.fileUrl);
        return fsPromises.unlink(filePath).catch((e: any) => {
          if (e.code !== 'ENOENT') console.error("Failed to delete physical file during reset:", e);
        });
      }
      return Promise.resolve();
    });

    // Stage 1 (Parallel): Delete leaves & child rows that have foreign keys pointing to other tables
    await Promise.all([
      Promise.allSettled(unlinkPromises),
      prisma.storedDocument.deleteMany({ where: { userId } }),
      prisma.shareTransfer.deleteMany({ where: { senderUserId: userId } }),
      prisma.export.deleteMany({ where: { userId } }),
      prisma.attendance.deleteMany({ where: { userId } }),
      prisma.assignmentCompletion.deleteMany({ where: { userId } }),
      prisma.classroomMember.deleteMany({ where: { userId } }),
    ]);

    // Stage 2 (Parallel): Tables unblocked by Stage 1 (attendance & completions gone)
    await Promise.all([
      prisma.timetableOverride.deleteMany({ where: { semester: { userId } } }),
      prisma.assignment.deleteMany({ where: { OR: [{ userId }, { classroom: { createdById: userId } }] } }),
      prisma.note.deleteMany({ where: { OR: [{ userId }, { classroom: { createdById: userId } }] } }),
      prisma.event.deleteMany({ where: { OR: [{ userId }, { semester: { userId } }] } }),
    ]);

    // Stage 3 (Parallel): Tables unblocked by Stage 2 (overrides, assignments, notes gone)
    await Promise.all([
      prisma.timetableSlot.deleteMany({ where: { semester: { userId } } }),
      prisma.classroom.deleteMany({ where: { createdById: userId } }).catch(() => {}),
    ]);

    // Stage 4: Delete subjects (unblocked by timetableSlots, overrides, attendance)
    await prisma.subject.deleteMany({ where: { userId } });

    // Stage 5 (Parallel): Delete semesters, reset user flags, and invalidate caches
    await Promise.all([
      prisma.semester.deleteMany({ where: { userId } }),
      prisma.user.update({
        where: { id: userId },
        data: {
          hasUsedVoiceMode: false,
          hasUsedPredictive: false,
          hasUsedPeerSync: false,
          onboardingDismissed: false,
          targetAttendance: 75,
        }
      }),
      CacheService.invalidateUser(userId),
    ]);

    return { success: true, message: "All app data reset successfully." };
  }

  static async resetSubjectAttendance(userId: string, subjectIds: string[]) {
    const overridesToDelete = await prisma.timetableOverride.findMany({
      where: {
        semester: { userId },
        OR: [
          { subjectId: { in: subjectIds } },
          { originalSlot: { subjectId: { in: subjectIds } } },
        ],
      },
      select: { id: true },
    });
    const overrideIds = overridesToDelete.map((o) => o.id);

    await prisma.attendance.deleteMany({
      where: {
        userId,
        OR: [
          { subjectId: { in: subjectIds } },
          ...(overrideIds.length > 0 ? [{ overrideId: { in: overrideIds } }] : []),
        ],
      },
    });

    // Clean up extra classes and slot overrides for these subjects to prevent phantom rows
    if (overrideIds.length > 0) {
      await prisma.timetableOverride.deleteMany({
        where: { id: { in: overrideIds } },
      });
    }

    return { success: true, message: "Subject attendance reset successfully." };
  }

  static async resetAllAttendance(userId: string) {
    await prisma.attendance.deleteMany({
      where: { userId },
    });

    // Also clear all timetable overrides (extra classes, cancelled, rescheduled)
    await prisma.timetableOverride.deleteMany({
      where: { semester: { userId } },
    });

    return { success: true, message: "All attendance records reset successfully." };
  }
}
